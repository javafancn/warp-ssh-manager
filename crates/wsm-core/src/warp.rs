use crate::model::Host;
use crate::paths::AppPaths;
use crate::ssh::{atomic_write, validate_alias};
use anyhow::{bail, Context, Result};
use serde::Serialize;
use std::fs;
use std::path::PathBuf;
use std::process::Command;
use uuid::Uuid;

const HEADER: &str = "# Generated by Warp SSH Manager. Do not edit; this file is application-managed.\n";

#[derive(Debug, Serialize)]
struct Config {
    name: String,
    title: String,
    color: &'static str,
    panes: Vec<Pane>,
}
#[derive(Debug, Serialize)]
struct Pane { id: &'static str, #[serde(rename="type")] kind: &'static str, commands: Vec<String> }

pub fn config_stem(id:Uuid) -> String { format!("wsm_{}",id.simple()) }

pub fn config_path(paths:&AppPaths, id: Uuid) -> PathBuf {
    paths.warp_configs.join(format!("{}.toml",config_stem(id)))
}

pub fn render_tab_config(host:&Host, group_name: Option<&str>) -> Result<String> {
    validate_alias(&host.alias)?;
    let color=match group_name.unwrap_or("").to_ascii_lowercase().as_str() {
        x if x.contains("prod") || x.contains("生产") => "red",
        x if x.contains("test") || x.contains("staging") || x.contains("测试") => "yellow",
        x if x.contains("dev") || x.contains("开发") => "green",
        _ => "blue",
    };
    let name=match group_name { Some(g) if !g.is_empty()=>format!("{g} / {}",host.name), _=>host.name.clone() };
    let config=Config { name, title:host.name.clone(), color,
        panes:vec![Pane{id:"main",kind:"terminal",commands:vec![format!("ssh {}",host.alias)]}] };
    Ok(format!("{HEADER}{}",toml::to_string_pretty(&config)?))
}

pub fn write_tab(paths:&AppPaths, host:&Host, group_name:Option<&str>) -> Result<PathBuf> {
    let path=config_path(paths,host.id);
    if path.exists() && !is_owned(&path)? { bail!("refusing to overwrite non-managed Warp config: {}",path.display()); }
    atomic_write(&path,&render_tab_config(host,group_name)?)?;
    Ok(path)
}

fn is_owned(path:&PathBuf) -> Result<bool> {
    if path.is_symlink() { return Ok(false); }
    let text=fs::read_to_string(path)?;
    Ok(text.starts_with(HEADER))
}

pub fn remove_tab(paths:&AppPaths,id:Uuid) -> Result<()> {
    let path=config_path(paths,id);
    if path.exists() && is_owned(&path)? { fs::remove_file(path)?; }
    Ok(())
}

pub fn open_tab(id:Uuid,new_window:bool,preview:bool) -> Result<()> {
    let scheme=if preview {"warppreview"} else {"warp"};
    let suffix=if new_window {"?new_window=true"}else{""};
    let uri=format!("{scheme}://tab_config/{}{suffix}",config_stem(id));
    let status=Command::new("open").arg(&uri).status().context("launching macOS open URL")?;
    if !status.success() { bail!("macOS open could not dispatch {uri}"); }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::model::{HostInput,HostSource};
    fn fixture()->Host{ HostInput{name:"API \"Blue\"".into(),alias:"prod-api".into(),hostname:"example.net".into(),
        username:"deploy".into(),port:2222,identity_file:None,proxy_jump:None,group_id:None,favorite:true}.into_host(HostSource::Managed) }
    #[test] fn toml_is_valid_and_quotes_names() {
        let text=render_tab_config(&fixture(),Some("Production")).unwrap();
        let doc:toml::Value=toml::from_str(&text).unwrap();
        assert_eq!(doc["name"].as_str(),Some("Production / API \"Blue\""));
        assert_eq!(doc["panes"][0]["commands"][0].as_str(),Some("ssh prod-api"));
        assert_eq!(doc["color"].as_str(),Some("red"));
    }
    #[test] fn generated_files_never_delete_user_content() {
        let dir=tempfile::tempdir().unwrap();let p=AppPaths{data_dir:dir.path().join("app"),
            ssh_config:dir.path().join("config"),managed_ssh:dir.path().join("managed"),warp_configs:dir.path().join("warp")};
        let h=fixture();let file=config_path(&p,h.id);
        fs::create_dir_all(&p.warp_configs).unwrap();fs::write(&file,"name = \"User\"\n").unwrap();
        assert!(write_tab(&p,&h,None).is_err());
        remove_tab(&p,h.id).unwrap();assert!(file.exists());
    }
}
